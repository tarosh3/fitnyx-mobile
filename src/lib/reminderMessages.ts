const SETS: Record<ReminderType, ReminderCopy[]> = {
  workout: WORKOUT,
  water: WATER,
  food: FOOD,
  snack: SNACK,
  custom: GENERIC,
};

export function pickReminderCopy(
  type: ReminderType,
  fallbackTitle?: string
): ReminderCopy {
  const pool = SETS[type] ?? GENERIC;
  const pick = pool[Math.floor(Math.random() * pool.length)];
  return {
    title: fallbackTitle && fallbackTitle.trim() ? fallbackTitle : pick.title,
    body: pick.body,
  };
}
