"""Rebuild the export-safe Anton outlines. Requires fonttools (build time only)."""
from pathlib import Path
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

root = Path(__file__).resolve().parents[1]
font = TTFont(root / 'node_modules/@expo-google-fonts/anton/400Regular/Anton_400Regular.ttf')
glyphs = font.getGlyphSet()
chars = '0123456789.,:/abcdefghijklmnopqrstuvwxyz%−- '
result = {}
for char in chars:
    name = font.getBestCmap().get(ord(char))
    if not name:
        continue
    path = SVGPathPen(glyphs)
    bounds = BoundsPen(glyphs)
    glyphs[name].draw(path)
    glyphs[name].draw(bounds)
    result[char] = {'path': path.getCommands(), 'advance': font['hmtx'][name][0], 'bounds': bounds.bounds or (0, 0, 0, 0)}
out = root / 'src/features/share/cards/numeralGeometry.ts'
out.write_text('// Generated by scripts/build-share-numerals.py from the bundled OFL Anton font.\n'
    '// Exact ink bounds avoid platform-specific font ascender/line-height clipping.\n'
    + 'export const NUMERAL_EM = ' + str(font['head'].unitsPerEm) + ';\n'
    + 'export const NUMERAL_GLYPHS: Record<string, { path: string; advance: number; bounds: [number, number, number, number] }> = '
    + json.dumps(result, separators=(',', ':')) + ';\n')
